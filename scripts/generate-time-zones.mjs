// Regenerates src/utils/timeZoneCountries.ts from the IANA time zone database.
//
//   node scripts/generate-time-zones.mjs [/usr/share/zoneinfo]
//
// zone.tab assigns each zone to one country. tzdata.zi adds the links, which
// matter because browsers often report legacy names ("Asia/Saigon",
// "Asia/Calcutta") rather than the current ones.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const zoneInfo = process.argv[2] ?? "/usr/share/zoneinfo";
const output = new URL("../src/utils/timeZoneCountries.ts", import.meta.url);

const countryByZone = new Map();
for (const line of readFileSync(join(zoneInfo, "zone.tab"), "utf8").split(
  "\n",
)) {
  if (line.startsWith("#") || line.trim() === "") continue;
  const [country, , zone] = line.split("\t");
  countryByZone.set(zone, country);
}

const links = new Map();
for (const line of readFileSync(join(zoneInfo, "tzdata.zi"), "utf8").split(
  "\n",
)) {
  if (!line.startsWith("L ")) continue;
  const [, target, name] = line.split(" ");
  links.set(name, target);
}

for (const [name, target] of links) {
  if (countryByZone.has(name)) continue;
  let resolved = target;
  for (let depth = 0; depth < 4 && !countryByZone.has(resolved); depth++) {
    resolved = links.get(resolved);
    if (resolved === undefined) break;
  }
  const country = countryByZone.get(resolved);
  if (country) countryByZone.set(name, country);
}

const zonesByCountry = new Map();
for (const [zone, country] of countryByZone) {
  if (!zonesByCountry.has(country)) zonesByCountry.set(country, []);
  zonesByCountry.get(country).push(zone);
}

const entries = [...zonesByCountry]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([country, zones]) => `  ${country}: "${zones.sort().join(" ")}",`);

writeFileSync(
  output,
  `// Generated by scripts/generate-time-zones.mjs from the IANA time zone
// database. Do not edit by hand.

/** Space-separated IANA time zone names, keyed by ISO 3166 country code. */
export const TIME_ZONES_BY_COUNTRY: Record<string, string> = {
${entries.join("\n")}
};
`,
);

console.log(
  `Wrote ${countryByZone.size} zones in ${zonesByCountry.size} countries`,
);
